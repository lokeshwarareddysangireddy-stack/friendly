function productImage(p: SeedProduct): string {
  const override = PRODUCT_IMAGE_OVERRIDES[p.slug];
  if (override) return `/images/products/${override}.jpg`;
  if (p.categorySlug === "medicines-and-health-essentials") {
    return "/images/categories/medicines-health.jpg";
  }
  return "/images/products/grocery-essentials.jpg";
}

